BASE_FLAGS = ['-std=gnu99', '-Wall', '-Wno-unused-function', '-Wno-unused-variable',
              '-Wno-unused-but-set-variable', '-Wno-attributes', '-Wno-unknown-pragmas',
              '-fno-common', '-fcallgraph-info=su,da']


def host_dir(prj):
    return prj.wsp('host')


def scope_components(prj, model):
    want = prj.get('scope.components') or [c['short'] for c in model['components']]
    return [c for c in model['components'] if c['short'] in want]


def comp_dirs(prj, comps):
    root = prj.resolve(prj.get('sources.root')) or prj.root
    out = {}
    for c in comps:
        dirs = prj.get('sources.component_dirs', {}).get(c['short'])
        if not dirs:
            continue
        for d in ([dirs] if isinstance(dirs, str) else dirs):
            p = (root / d).resolve()
            if p.is_dir():
                out.setdefault(c['short'], []).append(p)
    return out


def include_dirs(prj):
    """Configured include dirs, plus every component dir (out-of-scope headers are needed to compile
    and to mock the boundary) unless sources.include_all_component_dirs is false."""
    root = prj.resolve(prj.get('sources.root')) or prj.root
    out = []
    if prj.get('sources.include_all_component_dirs', True):
        for dirs in prj.get('sources.component_dirs', {}).values():
            for d in ([dirs] if isinstance(dirs, str) else dirs):
                if (root / d).is_dir():
                    out.append((root / d).resolve())
    for d in prj.get('sources.include_dirs', []):
        p = Path(d)
        p = p if p.is_absolute() else (root / d)
        if p.is_dir():
            out.append(p.resolve())
    return list(dict.fromkeys(out))


def rel(p: Path, base: Path) -> str:
    try:
        return os.path.relpath(p, base).replace('\\', '/')
    except ValueError:          # different drive on Windows
        return str(p).replace('\\', '/')


# --------------------------------------------------------------------------- yml

def cmd_yml(prj, model, force):
    hd = host_dir(prj)
    (hd / 'test').mkdir(parents=True, exist_ok=True)
    sup = hd / 'support'
    sup.mkdir(exist_ok=True)
    for name in ('swit_host.h',):
        src = ASSETS / 'host' / name
        if src.exists() and not (sup / name).exists():
            shutil.copyfile(src, sup / name)
    extra_sup = prj.resolve(prj.get('sources.support_dir'))
    target = hd / 'project.yml'
    if target.exists() and not force:
        print(f'{target} exists; use --force to regenerate')
        return 1
    comps = scope_components(prj, model)
    cdirs = comp_dirs(prj, comps)
    srcs = [d for ds in cdirs.values() for d in ds]
    glue = [prj.resolve(g) for g in prj.get('sources.glue_sources', [])]
    incs = list(dict.fromkeys(([extra_sup] if extra_sup else []) + srcs + include_dirs(prj)))
    flags = BASE_FLAGS + list(prj.get('sources.host_flags', []))
    text = YML.format(
        sources='\n'.join(f'    - {rel(d, hd)}' for d in srcs + [g.parent for g in glue if g]),
        includes='\n'.join(f'    - {rel(d, hd)}' for d in incs),
        defines='\n'.join(f'    - {d}' for d in dict.fromkeys(['SWIT_HOST_TEST'] + list(prj.get('sources.defines', [])))),
        flags='\n'.join(f'        - {f}' for f in flags),
        treat_as='\n'.join(f'    {k}: {v}' for k, v in (prj.get('sources.cmock_treat_as') or {}).items()),
    )
    target.write_text(text, encoding='utf-8', newline='\n')
    missing = [c['short'] for c in comps if c['short'] not in cdirs]
    print(f'wrote {target}: {len(srcs)} component dirs, {len(incs)} include dirs')
    if missing:
        print(f'  components without sources.component_dirs entry (not linked): {", ".join(missing)}')
    unmatched = []
    for d in srcs:
        heads = {p.stem.lower() for p in d.glob('*.h')}
        unmatched += [c.name for c in sorted(d.glob('*.c')) if c.stem.lower() not in heads]
    if unmatched:
        (hd / 'test' / 'swit_sources.txt').write_text(
            '\n'.join(f'TEST_SOURCE_FILE("{n}")' for n in unmatched) + '\n', encoding='utf-8')
        print(f'  {len(unmatched)} .c files have no same-named header -> tests must pull them in with '
              f'TEST_SOURCE_FILE(...) (list in test/swit_sources.txt)')
    return 0


# --------------------------------------------------------------------------- probe

def cmd_probe(prj, model):
    hd = host_dir(prj)
    gcc = prj.get('toolchain.gcc', 'gcc')
    comps = scope_components(prj, model)
    cdirs = comp_dirs(prj, comps)
    sup = [hd / 'support'] + ([prj.resolve(prj.get('sources.support_dir'))] if prj.get('sources.support_dir') else [])
    incs = sup + [d for ds in cdirs.values() for d in ds] + include_dirs(prj)
    args = [gcc, '-fsyntax-only', '-std=gnu99', '-DSWIT_HOST_TEST'] + \
        [f'-D{d}' for d in prj.get('sources.defines', [])] + [f'-I{p}' for p in incs if p and p.exists()]
    missing_h, errors, ok = {}, {}, 0
    for comp, ds in cdirs.items():
        for d in ds:
            for c in sorted(d.glob('*.c')):
                r = subprocess.run(args + [str(c)], capture_output=True, text=True, encoding='utf-8', errors='replace')
                if r.returncode == 0:
                    ok += 1
                    continue
                for m in re.finditer(r"fatal error: ([^:]+): No such file", r.stderr):
                    missing_h.setdefault(m.group(1).strip(), set()).add(f'{comp}/{c.name}')
                for m in re.finditer(r'error: (.+)', r.stderr):
                    msg = re.sub(r"'[^']*'", lambda x: x.group(0), m.group(1))[:140]
                    errors.setdefault(msg, set()).add(f'{comp}/{c.name}')
    print(f'probe: {ok} files compile cleanly')
    if missing_h:
        print('missing headers (add the real include dir, or a host stand-in under host/support/):')
        for h, fs in sorted(missing_h.items(), key=lambda x: -len(x[1])):
            print(f'  {h:40s} <- {", ".join(sorted(fs)[:5])}{" ..." if len(fs) > 5 else ""}')
    if errors:
        print('other errors (first 25):')
        for e, fs in list(sorted(errors.items(), key=lambda x: -len(x[1])))[:25]:
            print(f'  {e}  <- {", ".join(sorted(fs)[:3])}')
    return 0 if not (missing_h or errors) else 1


# --------------------------------------------------------------------------- boundary

def cmd_boundary(prj, model):
    hd = host_dir(prj)
    comps = scope_components(prj, model)
    inscope = {c['short'] for c in comps}
    provided = {i['name'] for i in model['interfaces'] if i['component'] in inscope}
    sig_of = {i['name']: i['signature'] for i in model['interfaces']}
    owner = {i['name']: i['component'] for i in model['interfaces']}
    lines = ['# Functions the in-scope components call outside the integration scope (from the SAD',
             '# dependency tables). Put their prototypes into boundary headers under host/support/',
             '# (or point scope.boundary_headers at real headers) and include mock_<header>.h in tests.', '']
    for c in comps:
        res = c.get('uses_resolved', {})
        outside = [f for f in c.get('uses', []) if res.get(f, f) not in provided]
        if not outside:
            continue
        lines.append(f'## {c["short"]}')
        for f in outside:
            real = res.get(f, f)
            where = owner.get(real, 'external (MCAL/BSW/LIB)')
            sig = sig_of.get(real) or c.get('uses_sig', {}).get(f) or f + '(...)'
            alias = f'  alias of {real}' if real != f else ''
            lines.append(f'{sig};    /* {where}{alias} */')
        lines.append('')
    p = hd / 'support' / 'swit_boundary_protos.txt'
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {p}')
    return 0


# --------------------------------------------------------------------------- stand-ins

def _public_header(dirs, names):
    """Header in the component dir that declares most of the component's interface names."""
    best, score = None, 0
    for d in dirs:
        for h in d.glob('*.h'):
            txt = h.read_text(encoding='utf-8', errors='replace')
            n = sum(1 for f in names if re.search(r'\b' + re.escape(f) + r'\b', txt))
            if n > score:
                best, score = h, n
    return best


def cmd_standins(prj, model, force):
    sup = host_dir(prj) / 'support'
    sup.mkdir(parents=True, exist_ok=True)
    inscope = {c['short'] for c in scope_components(prj, model)}
    all_dirs = comp_dirs(prj, model['components'])
    base_inc = prj.get('sources.standin_includes', [])
    made, bad_sigs = [], []
    for c in model['components']:
        if c['short'] in inscope or c['short'] not in all_dirs:
            continue
        itfs = [i for i in model['interfaces'] if i['component'] == c['short']]
        if not itfs:
            continue
        hdr = _public_header(all_dirs[c['short']], [i['name'] for i in itfs])
        if hdr is None:
            continue
        dst = sup / hdr.name
        if dst.exists() and not force:
            continue
        guard = re.sub(r'\W', '_', hdr.name.upper()) + '_SWIT_STANDIN'
        lines = [f'/* swit boundary stand-in for out-of-scope component {c["short"]} ({c.get("id") or "no SAD id"}).',
                 f' * Shadows {hdr.name}; prototypes taken from the SAD interface definitions. CMock mocks this file',
                 ' * (#include "mock_' + hdr.stem + '.h" in a test). Add types/macros the in-scope code needs by hand. */',
                 f'#ifndef {guard}', f'#define {guard}']
        lines += [f'#include "{h}"' for h in base_inc]
        lines.append('')
        for i in itfs:
            sig, ok = sanitize_signature(i['signature'])
            if ok:
                lines.append(f'{sig};    /* {i.get("id") or ""} */')
            else:
                bad_sigs.append((c['short'], i.get('id'), i['signature']))
                lines.append(f'/* SAD signature is not valid C, fix by hand: {i["signature"]}  ({i.get("id") or ""}) */')
        lines += ['', f'#endif /* {guard} */', '']
        dst.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
        made.append(dst.name)
    print(f'stand-ins written: {len(made)}  {", ".join(made)}')
    if bad_sigs:
        print(f'{len(bad_sigs)} SAD interface signature(s) are not valid C (SAD finding - report it upstream):')
        for comp, iid, sig in bad_sigs:
            print(f'  {comp:8s} {iid or "-":12s} {sig}')
    return 0


SIG_RE = re.compile(r'^\s*([A-Za-z_][\w\s\*]*?[\s\*])([A-Za-z_]\w*)\s*\(([^()]*)\)\s*;?\s*$')


def sanitize_signature(sig: str):
    """Repair the usual SAD transcription slips; return (signature, is_valid_c)."""
    s = (sig or '').replace(' / ', ' ').strip().rstrip(';')
    s = re.sub(r'\bVoid\b', 'void', s)
    s = re.sub(r'\b([A-Za-z]+_)\s+([a-z]\w*)\s*\(', r'\1\2(', s)        # "HSYS_ vidX(" -> "HSYS_vidX("
    m = SIG_RE.match(s)
    if not m:
        return s, False
    params = m.group(3).strip()
    if params and params not in ('void',) and not all(re.match(r'^[\w\s\*\[\]]+$', p.strip()) for p in params.split(',')):
        return s, False
    return f'{m.group(1).strip()} {m.group(2)}({params or "void"})', True


# --------------------------------------------------------------------------- skeleton

MARK_RE = re.compile(r'/\*\s*SWIT:\s*([^*]*?)\*/')


def existing_marks(test_dir: Path):
    have = set()
    for f in test_dir.glob('test_*.c'):
        for m in MARK_RE.finditer(f.read_text(encoding='utf-8', errors='replace')):
            have.update(x.strip() for x in m.group(1).split(',') if x.strip())
    return have


def cmd_skeleton(prj, model):
    hd = host_dir(prj)
    td = hd / 'test'
    td.mkdir(parents=True, exist_ok=True)
    reg = load_json(prj.wsp('cases', 'cases.json'))
    inscope = {c['short'] for c in scope_components(prj, model)}
    have = existing_marks(td)
    groups = {}
    for c in reg['cases']:
        if c['status'] != 'Active' or c['execution'] != 'host' or c['id'] in have:
            continue
        if c['category'] == 'interface' and c['component'] not in inscope:
            continue
        g = c['component'] or re.sub(r'[^a-z0-9]+', '_', c['anchor_name'].lower()).strip('_')[:40]
        groups.setdefault(f"{c['category'][:3]}_{g}".lower(), []).append(c)
    srcs_txt = (td / 'swit_sources.txt').read_text(encoding='utf-8') if (td / 'swit_sources.txt').exists() else ''
    written = []
    for g, cases in sorted(groups.items()):
        f = td / f'test_swit_{g}.c'
        if f.exists():
            f = td / f'test_swit_{g}_todo.c'
        body = [
            '/* generated by swit gen_ceedling.py skeleton - replace each TEST_IGNORE with the real test.',
            ' * Keep the SWIT marker above every test function: collect.py maps results through it. */',
            '#include "unity.h"',
            '#include "swit_host.h"',
            '/* real component headers of the integration under test, e.g. #include "ASMU_int.h" */',
            '/* boundary mocks, e.g. #include "mock_Adc.h" (see support/swit_boundary_protos.txt) */',
            '/* sources whose .c name differs from the header: copy the needed lines from swit_sources.txt',
            *[f' * {ln}' for ln in srcs_txt.splitlines()[:6]],
            ' */', '', 'void setUp(void) {}', 'void tearDown(void) {}', '']
        for c in cases:
            fn = re.sub(r'[^a-z0-9]+', '_', f"{c['id']}_{c['name']}".lower()).strip('_')[:70]
            anchor = c.get('anchor_id') or c['anchor_key']
            body += [f"/* SWIT: {c['id']} */",
                     f"/* {c['name']} | anchor {anchor} */",
                     f'void test_{fn}(void)', '{',
                     f'    TEST_IGNORE_MESSAGE("{c["id"]} not implemented yet");', '}', '']
        f.write_text('\n'.join(body), encoding='utf-8', newline='\n')
        written.append((f.name, len(cases)))
    for n, k in written:
        print(f'  {n}: {k} placeholder test(s)')
    print(f'skeleton: {sum(k for _, k in written)} cases without a test; {len(have)} already marked')
    return 0


def main() -> int:
    utf8_console()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--project', type=Path, required=True)
    ap.add_argument('cmd', choices=['yml', 'probe', 'boundary', 'standins', 'skeleton'])
    ap.add_argument('--force', action='store_true')
    a = ap.parse_args()
    prj = Project(a.project)
    model = load_json(prj.wsp('sad', 'arch_model.json'))
    if a.cmd == 'yml':
        return cmd_yml(prj, model, a.force)
    if a.cmd == 'probe':
        return cmd_probe(prj, model)
    if a.cmd == 'boundary':
        return cmd_boundary(prj, model)
    if a.cmd == 'standins':
        return cmd_standins(prj, model, a.force)
    return cmd_skeleton(prj, model)


if __name__ == '__main__':
    sys.exit(main())
