#!/usr/bin/env python3
"""Host SIL integration harness (Ceedling 1.x + Unity + CMock) for the in-scope components.

Sub-commands (run in this order, repeat probe until it is clean):
  yml        write <ws>/host/project.yml: real component dirs in :source, support + include dirs,
             CMock with :treat_externs :include, gcc -fcallgraph-info=su,da for call coverage
  probe      compile every in-scope .c with host gcc -fsyntax-only and summarise what breaks
             (missing headers, unknown types) -> tells Claude which host stand-ins go into support/
  boundary   write support/swit_boundary_protos.txt: prototypes of every function the in-scope
             components call outside the scope, taken from the SAD dependency tables - the raw
             material for the boundary headers that CMock mocks
  standins   for every OUT-of-scope component, write a same-named stand-in of its public header into
             support/ (support is first on the include path, so it shadows the real header) holding
             only the prototypes the SAD documents for that component; CMock mocks the stand-in.
             Existing stand-ins are never overwritten (hand edits survive); --force rewrites.
  skeleton   write one test file per component/behaviour group with a TEST_IGNORE placeholder per
             case and the marker comment that links tests to SWIT IDs; existing markers are kept,
             an existing file gets a *_todo.c companion instead of being overwritten

Marker comment (collect.py maps results to cases through it - never through function names):
  /* SWIT: SWIT-00012, SWIT-00031 */
  void test_asmu_reads_12v_through_hadc(void)

Usage: gen_ceedling.py --project P yml|probe|boundary|standins|skeleton [--force]
"""
