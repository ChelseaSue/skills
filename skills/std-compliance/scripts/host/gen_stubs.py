"""Generate neutral link stubs for symbols the integrated stack references outside the host build.

Reads the undefined references from the last Ceedling log, finds each symbol's prototype in the
project headers (AUTOSAR FUNC()/P2VAR() macros are understood), and writes
<support>/std_autostubs.c with one stub per symbol: non-void functions return 0 (= E_OK), output
parameters are left untouched. Tests pull it in with TEST_SOURCE_FILE("std_autostubs.c").

Per-test stub files (--stubs-out): MinGW cannot rely on weak symbols, so a test that links extra real modules
(e.g. the RTE glue) cannot share std_autostubs.c, which stubs those modules out. Run that test alone, then
`host stubs --stubs-out std_autostubs_<name>.c`: the file starts empty and holds only what that test still lacks;
the test names it with TEST_SOURCE_FILE instead of std_autostubs.c.

These stubs are deliberately dumb: a test that depends on a callout's behaviour (e.g. a DID read
function returning data) must provide a real fake in its own boundary file instead, and list the
symbol in host.stub_exclude so the generator skips it.
"""
import re
from pathlib import Path

import core
from host.gen_project import dirs

UNDEF = re.compile(r"undefined reference to `([A-Za-z_]\w*)'")


def _headers(prj):
    hd, td, sd = dirs(prj)
    roots = [sd] + [prj.p(i) for i in prj.get("host.include_dirs", [])]
    seen, out = set(), []
    for r in roots:
        if r and Path(r).is_dir():
            for h in sorted(Path(r).glob("*.h")):
                if h.name.lower() not in seen:
                    seen.add(h.name.lower())
                    out.append(h)
    return out


def _clean(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def _proto(sym, texts):
    rx = re.compile(r"(?:^|[;{}\n])\s*(?:extern\s+)?((?:FUNC\s*\([^)]*\)|[\w\s\*]+?))\s*\b" + re.escape(sym) +
                    r"\s*\(([^;{]*?)\)\s*;", re.S)
    for t in texts:
        m = rx.search(t)
        if m:
            ret = re.sub(r"\s+", " ", m.group(1)).strip()
            fm = re.match(r"FUNC\s*\(\s*([^,]+?)\s*,", ret)
            if fm:
                ret = fm.group(1)
            ret = re.sub(r"\b(extern|STATIC|static|inline|INLINE|LOCAL_INLINE)\b", "", ret).strip()
            params = re.sub(r"\s+", " ", m.group(2)).strip()
            return ret or "void", params or "void"
    return None


def _defined_in_sources(prj, syms):
    """Symbols that have a real definition somewhere under inputs.source_root -> {sym: file}.

    Stubbing a real utility (e.g. a memcpy wrapper) silently breaks the stack under test, so such
    symbols are reported and the real source should be added to host.sources instead."""
    root = prj.p(prj.get("inputs.source_root"))
    if not root or not root.is_dir():
        return {}
    pats = {s: re.compile(r"^[A-Za-z_][\w\s\*\(\),]*\b" + re.escape(s) + r"\s*\([^;]*$", re.M) for s in syms}
    found = {}
    for c in root.rglob("*.c"):
        try:
            t = _clean(c.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            continue
        for s, rx in pats.items():
            if s not in found and rx.search(t):
                found[s] = str(c.relative_to(root))
    return found


def generate(prj, out_name=None):
    hd, td, sd = dirs(prj)
    log = prj.wsp("results", "ceedling_stdout.log")
    text = log.read_text(encoding="utf-8", errors="ignore") if log.exists() else ""
    syms = sorted(set(UNDEF.findall(text)) - set(prj.get("host.stub_exclude", [])))
    if not syms:
        print("no undefined references in the last Ceedling log (run `stdc.py run` first)")
        return 1
    real = _defined_in_sources(prj, syms)
    if real:
        print("[warn] stubbed symbols that have REAL definitions in the project. Boundary modules (Det/Dem/NvM/BswM...) are fine;")
        print("       anything the stack under test relies on (memcpy wrappers, buffers, utilities) must be compiled for real:")
        for s_, f_ in sorted(real.items()):
            print(f"   {s_:40s} {f_}")
    texts = [_clean(h.read_text(encoding="utf-8", errors="ignore")) for h in _headers(prj)]
    # RTE glue and generated code often declare callees with a local `extern` in the .c file, not in a header
    from host.gen_project import expand_sources
    ds, files = expand_sources(prj)
    texts += [_clean(c.read_text(encoding="utf-8", errors="ignore")) for c in files + [x for d in ds for x in d.glob("*.c")]]
    out = sd / (out_name or "std_autostubs.c")
    old = out.read_text(encoding="utf-8") if out.exists() else ""
    have = set(re.findall(r"/\* stub: (\w+) \*/", old))
    lines = [old.rstrip("\n")] if old else [
        "/* generated by std-compliance (stdc.py host stubs): neutral link stubs for symbols outside the host build.",
        " * Non-void stubs return 0 (E_OK); outputs untouched. Replace with real fakes where a test depends on behaviour. */",
        '#include "Std_Types.h"', '#include "ComStack_Types.h"']
    incs = prj.get("host.stub_includes", [])
    for i in incs:
        if f'#include "{i}"' not in "\n".join(lines):
            lines.append(f'#include "{i}"')
    made, missing = 0, []
    for s in syms:
        if s in have:
            continue
        p = _proto(s, texts)
        if not p:
            missing.append(s)
            continue
        ret, params = p
        body = "" if ret.replace(" ", "") == "void" else f" return ({ret})0;"
        note = f" /* REAL DEFINITION EXISTS: {real[s]} - confirm stubbing is intended */" if s in real else ""
        lines.append(f"/* stub: {s} */ {ret} {s}({params}) {{{body} }}{note}")
        made += 1
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: +{made} stubs ({len(have)} existing)")
    if missing:
        print(f"[warn] no prototype found for {len(missing)} symbols (write them by hand): {', '.join(missing[:20])}")
    return 0
