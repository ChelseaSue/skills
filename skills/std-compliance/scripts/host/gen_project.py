"""Host-side behaviour tests for host-test checklist items: Ceedling project, skeletons, syntax probe.

The real protocol stack (e.g. LinIf/LinTp/PduR/Com/Dcm + the SWC callouts under test) is compiled for
the host; the boundary is the bus driver (Lin_/Can_ API) and anything below it, which tests replace
with the pack's bus stub (packs/<pack>/host/) or CMock mocks. Tests drive time in scheduler ticks
(std_host.h), never wall-clock time — real-time conformance is a `target` item, not a host test.

Config (std_project.json -> host):
  dir          working dir for the Ceedling project (default <ws>/host)
  test_dir     where tests live (default <dir>/test); keep it under configuration management
  support_dir  stand-in headers (default <dir>/support), placed FIRST on the include path
  sources      .c files, directories or globs that are compiled for real
  include_dirs extra include paths
  mocks        headers to CMock (only for documentation; tests must #include "mock_X.h" themselves)
  defines      preprocessor defines
"""
import glob
import re
import shutil
import subprocess
from pathlib import Path

import core

YML = """---
# generated by std-compliance (stdc.py host gen) - edit std_project.json and regenerate instead
:project:
  :build_root: build
  :use_test_preprocessor: :all
  :use_mocks: TRUE
  :use_exceptions: FALSE
  :test_file_prefix: test_
  :default_tasks:
    - test:all

:paths:
  :test:
    - {test}
  :source:
{source_dirs}
  :include:
{includes}

:files:
  :source:
{source_files}

:defines:
  :test:
{defines}

:flags:
  :test:
    :compile:
      :*:
        - -std=gnu99
        - -Wno-unused-function
        - -Wno-unused-variable
        - -Wno-unknown-pragmas
        - -fno-common

:cmock:
  :mock_prefix: mock_
  :when_no_prototypes: :warn
  :enforce_strict_ordering: FALSE
  :treat_externs: :include
  :treat_inlines: :include
  :plugins:
    - :ignore
    - :array
    - :expect_any_args
    - :ignore_arg
    - :callback
    - :return_thru_ptr

:plugins:
  :enabled:
    - report_tests_pretty_stdout
    - report_tests_raw_output_log
...
"""

SKELETON = """#include "unity.h"
#include "std_host.h"
/* Checklist item: {id} — {standard} {clause} {title}
 * Requirement (paraphrase): {req}
 * Write the test against the integrated stack: inject bus input through the boundary stub, run the
 * MainFunctions with STD_RUN_CYCLES, assert on what the stack transmits / reports.
 * Replace TEST_IGNORE with real assertions; keep the marker line above each test function. */

void setUp(void) {{}}
void tearDown(void) {{}}

/* STD: {id} */
void test_{fn}(void)
{{
    TEST_IGNORE_MESSAGE("not implemented: {id}");
}}
"""


def dirs(prj):
    h = prj.get("host", {})
    hd = prj.p(h.get("dir")) if h.get("dir") else prj.wsp("host")
    td = prj.p(h["test_dir"]) if h.get("test_dir") else hd / "test"
    sd = prj.p(h["support_dir"]) if h.get("support_dir") else hd / "support"
    return hd, td, sd


def _rel(p, base):
    try:
        return Path(p).resolve().relative_to(Path(base).resolve()).as_posix()
    except ValueError:
        import os
        return Path(os.path.relpath(Path(p).resolve(), Path(base).resolve())).as_posix()


def expand_sources(prj):
    files, ds = [], []
    for s in prj.get("host.sources", []):
        p = prj.p(s)
        if any(ch in s for ch in "*?["):
            files += [Path(x) for x in glob.glob(str(p), recursive=True) if x.endswith(".c")]
        elif p.is_dir():
            ds.append(p)
        elif p.exists():
            files.append(p)
        else:
            print(f"[warn] host source not found: {s}")
    return ds, files


def generate(prj, items):
    hd, td, sd = dirs(prj)
    for d in (hd, td, sd):
        d.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(core.SKILL / "assets" / "std_host.h", sd / "std_host.h")
    for pid in prj.get("packs", []):                       # pack bus stubs / helpers
        for f in (core.PACKS / pid / "host").glob("*.[ch]"):
            if not (sd / f.name).exists():
                shutil.copyfile(f, sd / f.name)
    ds, files = expand_sources(prj)
    incs = [sd] + [prj.p(i) for i in prj.get("host.include_dirs", [])]
    text = YML.format(
        test=_rel(td, hd), support=_rel(sd, hd),
        # support/ is a SOURCE path: helpers are linked only when a test names them with TEST_SOURCE_FILE.
        # Ceedling's :support: path would link them into every test, including bare skeletons.
        source_dirs="\n".join(f"    - {_rel(d, hd)}" for d in [sd] + ds),
        source_files="\n".join(f"    - {_rel(f, hd)}" for f in files) or "    []",
        includes="\n".join(f"    - {_rel(i, hd)}" for i in dict.fromkeys(incs)),
        defines="\n".join(f"    - {d}" for d in ["STD_HOST_TEST"] + list(prj.get("host.defines", []))))
    (hd / "project.yml").write_text(text, encoding="utf-8", newline="\n")
    marks, _ = core.test_marks(td)
    covered = {i for ids in marks.values() for i in ids}
    removed = 0
    wanted = {i["id"] for i in items}                      # items passed in are the applicable host-test items
    stale = 0
    for f in td.glob("test_std_*.c"):                     # skeletons superseded by real tests / no longer applicable
        t = f.read_text(encoding="utf-8", errors="ignore")
        m = core.MARK_RE.search(t)
        if not (core.SKELETON_MARK in t and m):
            continue
        ids = [x.strip() for x in m.group(1).split(",")]
        if all(x in covered for x in ids):
            f.unlink()
            removed += 1
        elif not any(x in wanted for x in ids):
            f.unlink()
            stale += 1
    made = 0
    for it in items:
        if it["id"] in covered:
            continue
        fn = re.sub(r"\W", "_", it["id"].lower())
        f = td / f"test_std_{fn}.c"
        if f.exists():
            continue
        f.write_text(SKELETON.format(id=it["id"], standard=it.get("standard", ""), clause=it.get("clause", ""),
                                     title=it.get("title", ""), req=it.get("requirement", "").replace("*/", "* /"),
                                     fn=fn), encoding="utf-8")
        made += 1
    print(f"wrote {hd / 'project.yml'} ({len(ds)} source dirs, {len(files)} source files, {len(incs)} include dirs)")
    print(f"host-test items {len(items)}: {len(covered & {i['id'] for i in items})} have tests, {made} skeletons created, "
          f"{removed} superseded / {stale} no-longer-applicable skeletons removed ({td})")


SKIP_DIRS = {".git", "build", "std_ws", "node_modules", "Debug", "Release", "settings"}


def config_drift(prj, srcs):
    """Same-name copies of compiled files elsewhere in the tree whose content differs.

    Typical case: a configurator writes fresh output to one folder while the IDE project compiles a hand-edited
    copy in another. Tests are only valid for the copy the target build compiles, and the drift itself is a
    configuration-management finding (regenerating would silently drop the hand edits)."""
    import os
    names = {Path(c).name: Path(c).resolve() for c in srcs}
    hdrs = {}
    for c in srcs:                                         # also compare the matching *_Cfg.h / *.h next to sources
        for h in Path(c).parent.glob("*.h"):
            hdrs.setdefault(h.name, h.resolve())
    want = {**hdrs, **names}
    found = []
    root = prj.p(prj.get("host.drift_root", "."))
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in fn:
            if f in want:
                q = (Path(dp) / f).resolve()
                if q != want[f] and _code(q) != _code(want[f]):
                    found.append((want[f], q))
    return found


def _code(path):
    """File content without comments and whitespace: generator headers (dates, versions) are not drift."""
    t = path.read_text(encoding="utf-8", errors="ignore")
    t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
    t = re.sub(r"//[^\n]*", "", t)
    return re.sub(r"\s+", "", t)


def probe(prj):
    hd, td, sd = dirs(prj)
    ds, files = expand_sources(prj)
    srcs = files + [c for d in ds for c in sorted(d.glob("*.c"))]
    drift = []
    for used, other in config_drift(prj, srcs):
        if "__attribute__((weak))" in other.read_text(encoding="utf-8", errors="ignore"):
            print(f"[weak]  {used.name}: {_rel(other, prj.base)} only holds weak defaults overridden by the compiled copy")
            continue
        drift.append((used, other))
        print(f"[drift] {used.name}: {_rel(used, prj.base)} (compiled here) != {_rel(other, prj.base)}")
    if drift:
        print(f"[drift] {len(drift)} same-name files differ in code (comments/whitespace ignored): confirm which copy the "
              f"target build compiles (IDE project / Makefile), make host.sources use that copy, record the drift as a finding")
    incs = [sd] + [prj.p(i) for i in prj.get("host.include_dirs", [])]
    gcc = prj.get("host.compiler", "gcc")
    args = [gcc, "-fsyntax-only", "-std=gnu99", "-DSTD_HOST_TEST"] + [f"-D{d}" for d in prj.get("host.defines", [])] + \
        [f"-I{p}" for p in incs if p and Path(p).exists()]
    missing, errors, ok = {}, {}, 0
    for c in srcs:
        r = subprocess.run(args + [str(c)], capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode == 0:
            ok += 1
            continue
        for m in re.finditer(r"fatal error: ([^:]+): No such file", r.stderr):
            missing.setdefault(m.group(1).strip(), set()).add(c.name)
        for m in re.finditer(r"error: (.+)", r.stderr):
            errors.setdefault(m.group(1)[:140], set()).add(c.name)
    print(f"probe: {ok}/{len(srcs)} files compile cleanly")
    for h, fs in sorted(missing.items(), key=lambda x: -len(x[1])):
        print(f"  missing header {h:36s} <- {', '.join(sorted(fs)[:4])}")
    for e, fs in list(sorted(errors.items(), key=lambda x: -len(x[1])))[:25]:
        print(f"  error {e}  <- {', '.join(sorted(fs)[:3])}")
    return 0 if not (missing or errors) else 1
